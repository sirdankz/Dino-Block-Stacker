#!/usr/bin/env python3
"""Compile the original menu PNGs into lossless indexed row runs. Requires Pillow."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SIZE = (512, 480)


def encode(image):
    colors, palette, pixels = {}, [], []
    for color in image.get_flattened_data():
        if color not in colors:
            colors[color] = len(palette)
            palette.append(color)
        pixels.append(colors[color])
    if len(palette) > 128:
        raise ValueError('Menu layers support up to 128 colors per compiled image.')
    runs, rows = [], [0]
    for y in range(SIZE[1]):
        x = 0
        while x < SIZE[0]:
            index, start = pixels[y * SIZE[0] + x], x
            x += 1
            while x < SIZE[0] and pixels[y * SIZE[0] + x] == index:
                x += 1
            runs.append((index << 9) | (x - start - 1))
        rows.append(len(runs))
    if len(runs) > 65535:
        raise ValueError('Too many menu row runs.')
    return palette, runs, rows


def array(name, ctype, values, formatter, width=12):
    return ['static const ' + ctype + ' ' + name + '[] = {'] + [
        '    ' + ','.join(formatter(v) for v in values[i:i + width]) + ','
        for i in range(0, len(values), width)
    ] + ['};']


def compose_frame(outer, inner):
    # Retain the inner outline and dotted trim. Its flat black fill would
    # otherwise darken the outer frame's translucent surface a second time.
    outline = inner.copy()
    outline.putdata([(0, 0, 0, 0) if p == (17, 19, 19, 241) else p
                     for p in inner.get_flattened_data()])
    return Image.alpha_composite(outer, outline)


def main():
    folder = ROOT / 'assets/menus'
    images = [Image.open(folder / name).convert('RGBA') for name in (
        'tetris_general_background.png', 'tetris_general_menu1.png',
        'tetris_general_menu2.png')]
    if any(im.size != SIZE for im in images):
        raise ValueError('Menu layers must be 512x480.')
    if images[0].getchannel('A').getextrema() != (255, 255):
        raise ValueError('The tileable background must be opaque.')
    # Use one panel fill while preserving the supplied border artwork.
    frame = compose_frame(images[1], images[2])
    text = ['/* Generated by tools/compile_menu_art.py; do not edit by hand. */',
            '#ifndef TA_MENU_SPRITES_H', '#define TA_MENU_SPRITES_H',
            '#include <stdint.h>']
    for label, im in [('background', images[0]), ('frame', frame)]:
        palette, runs, rows = encode(im)
        text.append('#define TA_MENU_' + label.upper() + '_COLORS ' + str(len(palette)) + 'u')
        values = [(a << 24) | (r << 16) | (g << 8) | b for r, g, b, a in palette]
        text += array('ta_menu_' + label + '_palette', 'uint32_t', values, lambda v: '0x%08xu' % v)
        text += array('ta_menu_' + label + '_runs', 'uint16_t', runs, lambda v: '0x%04x' % v)
        text += array('ta_menu_' + label + '_rows', 'uint16_t', rows, str)
        print(label + ': ' + str(len(palette)) + ' colors, ' + str(len(runs)) + ' row runs')
    text += ['#endif', '']
    (ROOT / 'src/xbox/ta_menu_sprites.h').write_text('\n'.join(text), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
