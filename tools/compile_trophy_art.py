"""Compile supplied 32x32 trophy frames and GIF timing. Requires Pillow."""
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
def compile_art():
 folder=ROOT/'assets/trophy';frames=[Image.open(folder/('trophy-%u.png'%i)).convert('RGBA') for i in range(1,9)]
 if any(im.size!=(32,32) for im in frames):raise ValueError('Trophy frames must be 32x32')
 animation=Image.open(folder/'trophy.gif')
 if animation.n_frames!=len(frames):raise ValueError('GIF timing and PNG frame counts differ')
 ends=[];elapsed=0
 for i in range(len(frames)):
  animation.seek(i);elapsed+=max(10,int(animation.info.get('duration',300)));ends.append(elapsed)
 colors={};palette=[];pixels=[]
 for im in frames:
  for p in im.get_flattened_data():
   if not p[3]:p=(0,0,0,0)
   if p not in colors:colors[p]=len(palette);palette.append(p)
   pixels.append(colors[p])
 if len(palette)>256:raise ValueError('Trophy palette exceeds 256 colors')
 lines=['/* Generated by tools/compile_trophy_art.py. */','#ifndef TA_TROPHY_SPRITES_H','#define TA_TROPHY_SPRITES_H','#include <stdint.h>','#define TA_TROPHY_FRAMES 8u','#define TA_TROPHY_SIZE 32u','#define TA_TROPHY_LOOP_MS %uu'%elapsed]
 lines+=['static const unsigned ta_trophy_frame_ends[8]={'+','.join(str(n)+'u' for n in ends)+'};','static const uint32_t ta_trophy_palette[]={'+','.join('0x%08xu'%((a<<24)|(r<<16)|(g<<8)|b) for r,g,b,a in palette)+'};','static const uint8_t ta_trophy_pixels[8*32*32]={']
 lines+=[' '+','.join(str(n) for n in pixels[i:i+32])+',' for i in range(0,len(pixels),32)];lines+=['};','#endif','']
 (ROOT/'src/xbox/ta_trophy_sprites.h').write_text('\n'.join(lines),encoding='utf-8',newline='\n')
 print('Trophy: 8 frames, %u colors, %u ms loop'%(len(palette),elapsed))
if __name__=='__main__':compile_art()
